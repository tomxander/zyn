def _capl_id(case_id: str) -> str:
    name = re.sub(r"\W+", "_", case_id).strip("_")
    return name if name[:1].isalpha() else "TC_" + name


def _capl_str(s: str) -> str:
    return s.replace("\\", "/").replace('"', "'").replace("\n", " ")[:200]


def capl(cases: list[dict], run_id: str) -> str:
    out = [CAPL_HEAD.format(run_id=run_id, label=PROTOTYPE_LABEL)]
    for c in cases:
        out.append(f"/* {c['case_id']}: {_capl_str(c['title'])}\n"
                   f"   Oracle ({c['oracle']['requirement_id']}): "
                   f"{_capl_str(c['oracle']['quote'])}\n"
                   f"   Expected: {_capl_str(c['expected'])} */")
        out.append(f"testcase {_capl_id(c['case_id'])}()\n{{")
        out.append("  long zt;\n  int zok;")  # CAPL wants local variables at the top
        out.append(f'  testCaseTitle("{c["case_id"]}", "{_capl_str(c["title"])}");')
        for v in c.get("open_values", []):
            out.append(f'  testCaseComment("Open value: {_capl_str(v)}");')
        if c["kind"] == "manual":
            out.append(f'  testCaseComment("Manual check: {_capl_str(c["expected"])}");')
            out.append('  testStepPass("manual", "Not automated; checked by a person.");')
            out.append("}\n")
            continue
        for s, wait, _span in _waits(c):
            if wait:
                out.append(f"  testWaitForTimeout({wait});")
            d = s["do"]
            if d == "set":
                out.append(f"  ${s['signal']} = {_num(s['value'])};")
            elif d == "stop":
                out.append(f'  ZynStopMessage("{s["message"]}");')
            elif d == "expect" and s.get("within_ms") is not None:
                out.append(f"  if (testWaitForSignalMatch({s['signal']}, {_num(s['value'])}, "
                           f"{int(s['within_ms'])}) == 1)")
                out.append(f'    testStepPass("check", "{s["signal"]} = {_num(s["value"])} '
                           f'within {int(s["within_ms"])} ms");')
                out.append("  else")
                out.append(f'    testStepFail("check", "{s["signal"]} did not reach '
                           f'{_num(s["value"])} within {int(s["within_ms"])} ms");')
            elif d in ("expect", "expect_absent"):
                ms = int(s.get("for_ms") or 0)
                want = "==" if d == "expect" else "!="
                out.append("  zok = 1;")
                out.append(f"  for (zt = 0; zt <= {ms}; zt += 10) {{ if (!(${s['signal']} {want} "
                           f"{_num(s['value'])})) zok = 0; testWaitForTimeout(10); }}")
                out.append(f'  if (zok) testStepPass("check", "{s["signal"]} {want} '
                           f'{_num(s["value"])} for {ms} ms");')
                out.append(f'  else testStepFail("check", "{s["signal"]} {want} '
                           f'{_num(s["value"])} did not hold for {ms} ms");')
            elif d == "expect_range":
                ms = int(s["after_ms"])
                lo = "-1e300" if s["low"] is None else _num(s["low"])
                hi = "1e300" if s["high"] is None else _num(s["high"])
                band = (f"at least {lo}" if s["high"] is None else f"at most {hi}"
                        if s["low"] is None else f"in {lo}..{hi}")
                out.append(f"  if (testWaitForSignalInRange({s['signal']}, {lo}, {hi}, {ms}) "
                           "== 1)")
                out.append(f'    testStepPass("check", "{s["signal"]} {band}");')
                out.append("  else")
                out.append(f'    testStepFail("check", "{s["signal"]} not {band} '
                           f'within {ms} ms");')
            elif d == "expect_period":
                out.append(f'  ZynCheckPeriod("{s["message"]}", {s["period_ms"]}, '
                           f'{s["tolerance_ms"]}, {s["count"]});')
        out.append("}\n")
    return "\n".join(out)


def capl_problems(source: str) -> list[str]:
    """Light structural checks (no CAPL compiler here): balanced braces and parentheses,
    every statement line ends in ; or a brace, unique testcase names."""
    problems = []
    body = re.sub(r"/\*.*?\*/", "", source, flags=re.DOTALL)
    body = re.sub(r'"(?:[^"\\]|\\.)*"', '""', body)
    for o, c in ("{}", "()"):
        if body.count(o) != body.count(c):
            problems.append(f"unbalanced {o}{c}: {body.count(o)} vs {body.count(c)}")
    names = re.findall(r"^testcase\s+(\w+)\s*\(", source, re.MULTILINE)
    if len(names) != len(set(names)):
        problems.append("duplicate testcase names")
    return problems


# ---- flat step table ---------------------------------------------------------------------


def steps_csv(cases: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=STEP_COLUMNS)
    w.writeheader()
    for c in cases:
        for n, s in enumerate(_ordered(c), start=1):
            w.writerow({
                "case_id": c["case_id"], "requirement_id": c["requirement_id"], "step": n,
                "at_ms": s["at_ms"], "action": s["do"],
                "signal_or_message": s.get("signal") or s.get("message") or "",
                "value": s.get("value", ""), "low": s.get("low", ""), "high": s.get("high", ""),
                "time_ms": s.get("within_ms") or s.get("for_ms") or s.get("after_ms") or "",
                "tolerance_ms": s.get("tolerance_ms", ""),
                "expected": c["expected"] if n == len(c["steps"]) else "",
                "oracle_quote": c["oracle"]["quote"] if n == 1 else ""})
    return buf.getvalue()
