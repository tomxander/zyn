"""The same generated cases for other test benches: Robot Framework, CANoe CAPL, and a flat
step table. Code from fixed templates, never model-written, never run here.

- Robot Framework (.robot): one test case per case, tagged with its requirement ID. The
  keywords (Set Signal, Expect Within, ...) are declared in a resource file whose bodies
  fail until you map them to your bench library, so nothing passes by accident.
- CAPL (.can): one testcase per case for a CANoe test module, using the database signals
  ($Signal) and the test feature set (testWaitForSignalMatch, testWaitForSignalInRange).
  Stopping a message and measuring a period depend on your simulation setup, so those steps
  call functions you implement, declared at the top and failing until you do.
- Step table (.csv): one row per step, for tools that import tabular test steps (ecu.test,
  test management tools) through their own column mapping. Zyn does not write native
  ecu.test packages: the format is proprietary and could not be checked here.

Every file says which run it came from and that it has not been run against hardware.
"""

from __future__ import annotations

import csv
import io
import re

from harness import PROTOTYPE_LABEL

STEP_COLUMNS = ["case_id", "requirement_id", "step", "at_ms", "action", "signal_or_message",
                "value", "low", "high", "time_ms", "tolerance_ms", "expected", "oracle_quote"]


def _ordered(case: dict) -> list[dict]:
    return sorted(case["steps"], key=lambda s: s["at_ms"])


def _waits(case: dict):
    """(step, wait before it in ms, time the step itself takes in ms)."""
    now = 0
    for s in _ordered(case):
        wait = max(0, s["at_ms"] - now)
        now = max(now, s["at_ms"])
        span = int(s.get("within_ms") or s.get("for_ms") or s.get("after_ms") or 0)
        if s["do"] == "expect_period":
            span = 0
        yield s, wait, span
        now += span


def _num(v) -> str:
    return str(int(v)) if isinstance(v, float) and v.is_integer() else str(v)


# ---- Robot Framework ---------------------------------------------------------------------

ROBOT_RESOURCE = """*** Settings ***
Documentation    Keywords the Zyn-generated suite uses. {label}
...              Map each keyword to your bench library (CAN interface, SIL or HIL).
...              Until you do, every keyword fails, so no test can pass by accident.

*** Keywords ***
Set Signal
    [Arguments]    ${{signal}}    ${{value}}
    Fail    Not mapped to a bench: Set Signal ${{signal}} ${{value}}

Stop Message
    [Arguments]    ${{message}}
    Fail    Not mapped to a bench: Stop Message ${{message}}

Expect Within
    [Arguments]    ${{signal}}    ${{value}}    ${{ms}}
    Fail    Not mapped to a bench: Expect Within ${{signal}} ${{value}} ${{ms}}

Expect For
    [Arguments]    ${{signal}}    ${{value}}    ${{ms}}
    Fail    Not mapped to a bench: Expect For ${{signal}} ${{value}} ${{ms}}

Expect Absent
    [Arguments]    ${{signal}}    ${{value}}    ${{ms}}
    Fail    Not mapped to a bench: Expect Absent ${{signal}} ${{value}} ${{ms}}

Expect In Range After
    [Arguments]    ${{signal}}    ${{low}}    ${{high}}    ${{ms}}
    Fail    Not mapped to a bench: Expect In Range After ${{signal}} ${{low}} ${{high}} ${{ms}}

Expect Period
    [Arguments]    ${{message}}    ${{period_ms}}    ${{tolerance_ms}}    ${{count}}
    Fail    Not mapped to a bench: Expect Period ${{message}} ${{period_ms}}
"""


def _robot_text(s: str) -> str:
    return re.sub(r"\s{2,}", " ", s.replace("\n", " ")).replace("|", "/").strip()


def robot(cases: list[dict], run_id: str) -> tuple[str, str]:
    """(suite, resource) texts."""
    out = ["*** Settings ***",
           (f"Documentation    Test cases generated by Zyn Anvil, run {run_id}. "
           f"{PROTOTYPE_LABEL}"),
           ("...              Not run against any hardware or simulator here. Open values were "
           "assumed by the generator; replace them before relying on a result."),
           "Resource         zyn_keywords.resource", "", "*** Test Cases ***"]
    for c in cases:
        out.append(f"{c['case_id']} {_robot_text(c['title'])}")
        doc = (f"Oracle ({c['oracle']['requirement_id']}): {c['oracle']['quote']} "
               f"Expected: {c['expected']}")
        out.append(f"    [Documentation]    {_robot_text(doc)}")
        tags = [c["requirement_id"], c["template"], c["kind"]]
        if c.get("open_values"):
            tags.append("open-values")
        out.append("    [Tags]    " + "    ".join(tags))
        if c["kind"] == "manual":
            out.append(f"    Skip    Manual check: {_robot_text(c['expected'])}")
            out.append("")
            continue
        for s, wait, _span in _waits(c):
            if wait:
                out.append(f"    Sleep    {wait}ms")
            d = s["do"]
            if d == "set":
                out.append(f"    Set Signal    {s['signal']}    {_num(s['value'])}")
            elif d == "stop":
                out.append(f"    Stop Message    {s['message']}")
            elif d == "expect" and s.get("within_ms") is not None:
                out.append(f"    Expect Within    {s['signal']}    {_num(s['value'])}    "
                           f"{int(s['within_ms'])}")
            elif d == "expect":
                out.append(f"    Expect For    {s['signal']}    {_num(s['value'])}    "
                           f"{int(s.get('for_ms') or 0)}")
            elif d == "expect_absent":
                out.append(f"    Expect Absent    {s['signal']}    {_num(s['value'])}    "
                           f"{int(s['for_ms'])}")
            elif d == "expect_range":
                lo = "None" if s["low"] is None else _num(s["low"])
                hi = "None" if s["high"] is None else _num(s["high"])
                out.append(f"    Expect In Range After    {s['signal']}    {lo}    {hi}    "
                           f"{int(s['after_ms'])}")
            elif d == "expect_period":
                out.append(f"    Expect Period    {s['message']}    {s['period_ms']}    "
                           f"{s['tolerance_ms']}    {s['count']}")
        out.append("")
    return "\n".join(out) + "\n", ROBOT_RESOURCE.format(label=PROTOTYPE_LABEL)


