"""Write generated cases as a pytest module. Code from a fixed template, never model-written.

The module talks to a `bench` fixture that the team's own test environment provides
(CAN interface, SIL or HIL). The scripts have not been run against any hardware."""

from __future__ import annotations

import re

from harness import PROTOTYPE_LABEL

HEADER = '''"""Test cases generated by Zyn Anvil from approved test specs. {label}

Run {run_id}. Not run against any hardware or simulator here. Each test drives a `bench`
fixture your test environment must provide:

    bench.set(signal, value)            send an input signal value (keeps sending it)
    bench.stop(message)                 stop sending an input message
    bench.wait_ms(ms)                   let time pass
    bench.expect_within(signal, value, ms) -> bool   value seen within ms
    bench.expect_for(signal, value, ms) -> bool      value held for ms
    bench.periods(message, count) -> list[float]     next count intervals in ms
    bench.value_after(signal, ms) -> float           the signal's value ms from now

Values listed as open in a docstring were assumed by the generator because the requirement
does not give them. Replace them before relying on the result.
"""
'''


def _name(case_id: str) -> str:
    return "test_" + re.sub(r"\W+", "_", case_id).strip("_").lower()


def case_function(case: dict) -> str:
    doc = [f"{case['case_id']}: {case['title']}.",
           f"Oracle ({case['oracle']['requirement_id']}): \"{case['oracle']['quote']}\"",
           f"Expected: {case['expected'].rstrip('.')}.", f"Why these values: {case['boundary_rationale']}"]
    doc += [f"Open value: {v}" for v in case.get("open_values", [])]
    body = ['    """' + "\n    ".join(d.replace('"""', "'''") for d in doc) + '\n    """']
    if case["kind"] == "manual":
        body.append(f"    pytest.skip({case['expected']!r})")
    now = 0
    for s in sorted(case["steps"], key=lambda s: s["at_ms"]):
        if s["at_ms"] > now:
            body.append(f"    bench.wait_ms({s['at_ms'] - now})")
            now = s["at_ms"]
        if s["do"] == "set":
            body.append(f"    bench.set({s['signal']!r}, {s['value']!r})")
        elif s["do"] == "stop":
            body.append(f"    bench.stop({s['message']!r})")
        elif s["do"] == "expect":
            if s.get("within_ms") is not None:
                body.append(f"    assert bench.expect_within({s['signal']!r}, {s['value']!r}, "
                            f"{int(s['within_ms'])})")
            else:
                body.append(f"    assert bench.expect_for({s['signal']!r}, {s['value']!r}, "
                            f"{int(s.get('for_ms') or 0)})")
            now += int(s.get("within_ms") or s.get("for_ms") or 0)
        elif s["do"] == "expect_range":
            body.append(f"    v = bench.value_after({s['signal']!r}, {int(s['after_ms'])})")
            if s["low"] is not None:
                body.append(f"    assert v >= {s['low']!r}")
            if s["high"] is not None:
                body.append(f"    assert v <= {s['high']!r}")
            now += int(s["after_ms"])
        elif s["do"] == "expect_absent":
            body.append(f"    assert not bench.expect_within({s['signal']!r}, {s['value']!r}, "
                        f"{int(s['for_ms'])})")
            now += int(s["for_ms"])
        elif s["do"] == "expect_period":
            body.append(f"    gaps = bench.periods({s['message']!r}, {s['count']})")
            body.append(f"    assert len(gaps) == {s['count']}")
            body.append(f"    assert all(abs(g - {s['period_ms']}) <= {s['tolerance_ms']} "
                        "for g in gaps)")
    return f"\n\ndef {_name(case['case_id'])}(bench):\n" + "\n".join(body) + "\n"


def module(cases: list[dict], run_id: str) -> str:
    head = HEADER.format(label=PROTOTYPE_LABEL, run_id=run_id)
    if any(c["kind"] == "manual" for c in cases):
        head += "\nimport pytest\n"
    return head + "".join(case_function(c) for c in cases)


def lint(source: str) -> list[str]:
    """Compiles the module and runs ruff on it. Returns problems; empty means clean."""
    import subprocess
    import sys
    import tempfile
    from pathlib import Path

    try:
        compile(source, "generated_tests.py", "exec")
    except SyntaxError as e:
        return [f"syntax error: {e}"]
    with tempfile.TemporaryDirectory() as d:
        f = Path(d) / "test_generated.py"
        f.write_text(source, encoding="utf-8")
        r = subprocess.run([sys.executable, "-m", "ruff", "check", "--no-cache", "--isolated",
                            "--line-length", "120", str(f)], check=False,
                           capture_output=True, text=True)
    return [] if r.returncode == 0 else [line for line in r.stdout.splitlines() if line][:20]
