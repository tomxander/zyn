"""Export approved requirements: JSON (full record), XLSX (for people), ReqIF (for ALM tools
such as DOORS or Codebeamer). Only approved items are exported. Each export is logged with
file hashes."""

from __future__ import annotations

import hashlib
import json
import uuid
from datetime import UTC, datetime
from pathlib import Path
from xml.sax.saxutils import escape

from harness import PROTOTYPE_LABEL
from harness.audit.store import AuditStore
from harness.config import PROJECT_ROOT
from harness.sift.pipeline import display_id

COLUMNS = [
    ("id", "ID"), ("subsystem_id", "Subsystem"), ("section_number", "Section"),
    ("text", "Requirement"), ("modal", "Modal"), ("req_type", "Type"),
    ("verification_method", "Verification"), ("quality_flags", "Quality flags"),
    ("asil_hint", "ASIL hint (model suggestion)"), ("source_quote", "Source quote"),
    ("page", "Source page"), ("quote_offset", "Quote position in section"),
    ("source_document", "Source document"), ("source_sha256", "Source SHA-256"),
    ("version", "Version"), ("approved_by", "Approved by"), ("approved_at", "Approved at"),
    ("override_reason", "Override reason"), ("generated_by", "Generated by"),
    ("open_questions", "Open questions for spec author"),
]


def collect(audit: AuditStore, run_id: str) -> list[dict]:
    rows = []
    events = audit.events(run_id=run_id)
    doc = audit.get_item(f"DOC-{run_id}")["payload"]
    for it in audit.approved_items(run_id, "requirement"):
        approval = [e for e in events if e["object_id"] == it["item_id"]
                    and e["action"] == "approved" and e["object_version"] == it["version"]][-1]
        p = it["payload"]
        d = approval["detail"] or {}
        rows.append({
            **p,
            "id": display_id(it["item_id"]),
            "version": it["version"],
            "quality_flags": ", ".join(p.get("quality_flags", [])),
            "approved_by": approval["actor"],
            "page": p.get("page") or "",
            "quote_offset": "-".join(map(str, p["quote_offset"])) if p.get("quote_offset")
            else "",
            "source_document": doc["filename"], "source_sha256": doc["sha256"],
            "approved_at": approval["ts"],
            "override_reason": d.get("comment") if d.get("ai_override") else "",
            "open_questions": "; ".join((p.get("clarification") or {}).get("open_questions",
                                                                          [])),
        })
    return rows


def _write_xlsx(rows: list[dict], path: Path, run_id: str) -> None:
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill

    wb = Workbook()
    ws = wb.active
    ws.title = "Requirements"
    ws.append([PROTOTYPE_LABEL + f" Run {run_id}. Approved requirements only."])
    ws["A1"].font = Font(bold=True)
    ws.append([h for _, h in COLUMNS])
    for c in ws[2]:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="DDDDDD")
    for r in rows:
        ws.append([str(r.get(k, "")) for k, _ in COLUMNS])
    widths = {"Requirement": 70, "Source quote": 60, "Override reason": 40}
    for i, (_, h) in enumerate(COLUMNS, start=1):
        ws.column_dimensions[ws.cell(2, i).column_letter].width = widths.get(h, 16)
    ws.freeze_panes = "B3"
    wb.save(path)


def _reqif(rows: list[dict], title: str, run_id: str,
           columns: list[tuple[str, str]] | None = None) -> str:
    """ReqIF 1.2: one string datatype, one spec-object type with an attribute per column,
    one specification listing the requirements in order."""
    now = datetime.now(UTC).isoformat(timespec="seconds")
    attrs = [(k, h, f"AD-{k}") for k, h in (columns or COLUMNS)]

    def x(s: object) -> str:
        return escape(str(s), {'"': "&quot;"})

    defs = "".join(
        f'<ATTRIBUTE-DEFINITION-STRING IDENTIFIER="{aid}" LONG-NAME="{x(h)}" '
        f'LAST-CHANGE="{now}"><TYPE><DATATYPE-DEFINITION-STRING-REF>DT-STRING'
        f'</DATATYPE-DEFINITION-STRING-REF></TYPE></ATTRIBUTE-DEFINITION-STRING>'
        for _, h, aid in attrs)
    objects, hier = [], []
    for r in rows:
        oid = "SO-" + r["id"]
        vals = "".join(
            f'<ATTRIBUTE-VALUE-STRING THE-VALUE="{x(r.get(k, ""))}"><DEFINITION>'
            f'<ATTRIBUTE-DEFINITION-STRING-REF>{aid}</ATTRIBUTE-DEFINITION-STRING-REF>'
            f'</DEFINITION></ATTRIBUTE-VALUE-STRING>' for k, _, aid in attrs)
        objects.append(
            f'<SPEC-OBJECT IDENTIFIER="{x(oid)}" LONG-NAME="{x(r["id"])}" LAST-CHANGE="{now}">'
            f'<TYPE><SPEC-OBJECT-TYPE-REF>SOT-REQ</SPEC-OBJECT-TYPE-REF></TYPE>'
            f'<VALUES>{vals}</VALUES></SPEC-OBJECT>')
        hier.append(
            f'<SPEC-HIERARCHY IDENTIFIER="SH-{x(r["id"])}" LAST-CHANGE="{now}">'
            f'<OBJECT><SPEC-OBJECT-REF>{x(oid)}</SPEC-OBJECT-REF></OBJECT></SPEC-HIERARCHY>')
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<REQ-IF xmlns="http://www.omg.org/spec/ReqIF/20110401/reqif.xsd">'
        f'<THE-HEADER><REQ-IF-HEADER IDENTIFIER="H-{uuid.uuid4().hex}">'
        f'<COMMENT>{x(PROTOTYPE_LABEL)} Run {x(run_id)}</COMMENT>'
        f'<CREATION-TIME>{now}</CREATION-TIME><REQ-IF-TOOL-ID>zyn-harness</REQ-IF-TOOL-ID>'
        f'<REQ-IF-VERSION>1.0</REQ-IF-VERSION><SOURCE-TOOL-ID>zyn-harness</SOURCE-TOOL-ID>'
        f'<TITLE>{x(title)}</TITLE></REQ-IF-HEADER></THE-HEADER>'
        '<CORE-CONTENT><REQ-IF-CONTENT>'
        f'<DATATYPES><DATATYPE-DEFINITION-STRING IDENTIFIER="DT-STRING" LONG-NAME="String" '
        f'LAST-CHANGE="{now}" MAX-LENGTH="10000"/></DATATYPES>'
        f'<SPEC-TYPES><SPEC-OBJECT-TYPE IDENTIFIER="SOT-REQ" LONG-NAME="Requirement" '
        f'LAST-CHANGE="{now}"><SPEC-ATTRIBUTES>{defs}</SPEC-ATTRIBUTES></SPEC-OBJECT-TYPE>'
        f'<SPECIFICATION-TYPE IDENTIFIER="ST-SPEC" LONG-NAME="Specification" '
        f'LAST-CHANGE="{now}"/></SPEC-TYPES>'
        f'<SPEC-OBJECTS>{"".join(objects)}</SPEC-OBJECTS>'
        f'<SPECIFICATIONS><SPECIFICATION IDENTIFIER="SPEC-{x(run_id)}" LONG-NAME="{x(title)}" '
        f'LAST-CHANGE="{now}"><TYPE><SPECIFICATION-TYPE-REF>ST-SPEC</SPECIFICATION-TYPE-REF>'
        f'</TYPE><CHILDREN>{"".join(hier)}</CHILDREN></SPECIFICATION></SPECIFICATIONS>'
        '</REQ-IF-CONTENT></CORE-CONTENT></REQ-IF>\n'
    )


def export(audit: AuditStore, run_id: str, actor: str, out_dir: Path | None = None) -> dict:
    rows = collect(audit, run_id)
    if not rows:
        raise ValueError("No approved requirements in this run. Nothing to export.")
    out = out_dir or PROJECT_ROOT / "runs" / "exports" / run_id
    out.mkdir(parents=True, exist_ok=True)
    title = audit.get_item(f"DOC-{run_id}")["payload"]["title"]
    files = {
        "json": out / "requirements.json",
        "xlsx": out / "requirements.xlsx",
        "reqif": out / "requirements.reqif",
    }
    files["json"].write_text(json.dumps(
        {"label": PROTOTYPE_LABEL, "run_id": run_id, "document": title, "requirements": rows},
        indent=2, ensure_ascii=False), encoding="utf-8")
    _write_xlsx(rows, files["xlsx"], run_id)
    files["reqif"].write_text(_reqif(rows, title, run_id), encoding="utf-8")
    hashes = {k: hashlib.sha256(p.read_bytes()).hexdigest() for k, p in files.items()}
    audit.log_event(actor, "exported", run_id=run_id, object_type="requirement",
                    detail={"count": len(rows), "files": {k: str(p) for k, p in files.items()},
                            "sha256": hashes})
    return {"count": len(rows), "files": {k: str(p) for k, p in files.items()}}
